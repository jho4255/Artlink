/**
 * 경력 항목을 여러 열에 나눠 담는다 (공개 작가 페이지 / 마이페이지 읽기 뷰 공용).
 *
 * **왜 grid 를 안 쓰는가.**
 * `grid ... lg:grid-cols-3` 은 한 **행**의 높이가 그 행에서 제일 긴 칸에 맞춰진다.
 * 실제 데이터가 그렇다 — 단체전은 20줄인데 개인전·아트페어는 2~3줄이다. 그러면
 *
 *     [학력]   [개인전]  [단체전]      ← 행 높이 = 단체전(20줄)
 *     (빈 칸이 17줄)
 *     [아트페어] [수상및선정]           ← 저 아래에서 시작
 *
 * 이 되어 '수상 및 선정'이 개인전에서 한참 떨어진다. `items-start` 를 줘도 칸 안에서
 * 위로 붙을 뿐 **행 높이 자체는 안 줄어든다**.
 *
 * **왜 CSS columns 도 아닌가.** 신문 단(`columns-3`)은 세로로 채우며 브라우저가 알아서
 * 높이를 맞춘다. 그래서 어떤 항목이 어느 열에 갈지 예측이 안 된다(예전에 개인전+단체전이
 * 한 열에 몰리고 아트페어만 옆으로 갔다).
 *
 * **그래서 라운드로빈이다.** i번째 항목을 i%n 열에 넣는다. 읽는 순서(좌→우)가 그대로 유지되고,
 * 각 열은 자기 내용만큼만 높이를 쓴다. 3열에서 [학력 개인전 단체전 아트페어 수상] 은
 *
 *     열0: 학력, 아트페어
 *     열1: 개인전, 수상 및 선정   ← 개인전 바로 아래
 *     열2: 단체전
 *
 * 가 되어 원하는 배치가 나온다.
 */
/**
 * @param weightOf 항목의 '길이'(줄 수). 생략하면 전부 1로 보고 단순히 돌아가며 담는다.
 *
 * 단순 라운드로빈(i%n)으로는 **2열에서 무너진다**. 실측 기준 [학력3 개인전3 단체전20 아트페어3 수상3]:
 *     열0: 학력, 단체전, 수상  (26줄)
 *     열1: 개인전, 아트페어      (6줄)
 * 수상이 20줄짜리 단체전 아래로 밀려 개인전에서 1180px 떨어졌다(오른쪽은 텅 빈 채).
 * 그래서 **그때그때 제일 짧은 열에 넣는다**(항목 순서는 그대로 훑으므로 좌→우 흐름은 유지).
 *     열0: 학력, 단체전 (23줄) / 열1: 개인전, 아트페어, 수상 (9줄)
 * 3열에서는 라운드로빈과 같은 결과가 나온다 — 열0[학력,아트페어] 열1[개인전,수상] 열2[단체전].
 */
export function splitIntoColumns<T>(items: T[], columns: number, weightOf?: (item: T) => number): T[][] {
  const n = Math.max(1, Math.trunc(columns) || 1);
  const out: T[][] = Array.from({ length: n }, () => []);
  const height = new Array(n).fill(0);

  for (const item of items) {
    // 아직 안 쓴 열이 있으면 거기부터 — 빈 열을 남긴 채 한 열에 쌓이지 않게
    let target = out.findIndex(col => col.length === 0);
    if (target === -1) {
      target = 0;
      for (let i = 1; i < n; i++) if (height[i] < height[target]) target = i;
    }
    out[target].push(item);
    // 제목 줄이 있으므로 항목 자체에도 최소 높이가 있다(+1)
    height[target] += Math.max(1, weightOf ? weightOf(item) : 1) + 1;
  }

  // 항목보다 열이 많으면 빈 열이 생긴다 — 그리면 gap 만큼 오른쪽에 빈 공간이 남으므로 잘라낸다
  return out.filter(col => col.length > 0);
}
