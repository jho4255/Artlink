/** 이 코드 포인트를 Pretendard 가 그리는가 — 이진 탐색 */
export function pretendardHas(cp: number): boolean {
  let lo = 0;
  let hi = PRETENDARD_RANGES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [a, b] = PRETENDARD_RANGES[mid]!;
    if (cp < a) hi = mid - 1;
    else if (cp > b) lo = mid + 1;
    else return true;
  }
  return false;
}
